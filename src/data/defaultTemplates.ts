export const UNIT_CONVERSIONS = {
  inToMm: (val: number) => +(val * 25.4).toFixed(1),
  mmToIn: (val: number) => +(val / 25.4).toFixed(2),
  inToCm: (val: number) => +(val * 2.54).toFixed(2),
  cmToIn: (val: number) => +(val / 2.54).toFixed(2),
  convert: (val: number, from: LabelDimensionUnit, to: LabelDimensionUnit): number => {
    if (from === to) return val;
    // convert to inches first
    let inVal = val;
    if (from === 'mm') inVal = val / 25.4;
    else if (from === 'cm') inVal = val / 2.54;

    // convert from inches to target
    if (to === 'in') return +inVal.toFixed(2);
    if (to === 'mm') return +(inVal * 25.4).toFixed(1);
    if (to === 'cm') return +(inVal * 2.54).toFixed(2);
    return val;
  },
};

